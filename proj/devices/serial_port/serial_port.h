#ifndef SERIAL_PORT_H
#define SERIAL_PORT_H

#include <lcom/lcf.h>
#include "queue.h"

/**
 * @brief The IRQ line number for COM1 serial port.
 */
#define IRQ_COM1 4

/**
 * @brief This is used as a numerator to set the bit-rate (number of bits trasmitted per second) of the serial port (clock frequency divided by 16).
 */
#define DIVIDED_CLOCK_FREQUENCY 115200

/**
 * @brief The base address of COM1 serial port registers.
 */
#define COM1_BASE 0x3F8

/**
 * @brief The offset of the Transmitter Holding Register (THR) from the base address of a UART serial port. This register is used to write the data that will be transmitted by the serial port.
 */
#define THR_OFFSET 0

/**
 * @brief The offset of the Receiver Buffer Register (RBR) from the base address of a UART serial port. This register is used to read the data that has been received by the serial port.
 */
#define RBR_OFFSET 0

/** 
 * @brief The offset of the Interrupt Enable Register (IER) from the base address of a UART serial port.
*/
#define IER_OFFSET 1

#define IER_RECEIVED_DATA_AVAILABLE_INTERRUPT BIT(0)
#define IER_TRANSMITTER_HOLDING_REGISTER_EMPTY_INTERRUPT BIT(1)
#define IER_LINE_STATUS_INTERRUPT BIT(2)
#define IER_CLEAR_INTERRUPTS 0xF8 // clears only the first 3 bits of the IER

/**
 * @brief The offset of the Interrupt Identification Register (IIR) from the base address of a UART serial port when this address is accessed for reading. This register is used to identify the cause of an interrupt generated by the serial port.
 */
#define IIR_OFFSET 2

#define IIR_NO_INTERRUPT_PENDING BIT(0)
#define IIR_INTERRUPT_TYPE(iir) (iir >> 1) & 0x7 // bits 1, 2 and 3 of the IIR indicate the type of interrupt that is pending
#define IIR_RECEIVER_LINE_STATUS_INTERRUPT 0x3
#define IIR_RECEIVED_DATA_AVAILABLE_INTERRUPT 0x2
#define IIR_CHARACTER_TIMEOUT_INTERRUPT 0x6
#define IIR_TRANSMITTER_HOLDING_REGISTER_EMPTY_INTERRUPT 0x1
#define IIR_FIFOS_ENABLED BIT(7) | BIT(6)

/**
 * @brief The offset of the FIFO Control Register (FCR) from the base address of a UART serial port, when this address is accessed for writing.
 */
#define FCR_OFFSET 2

/**
 * @brief The bit of FCR for enabling the FIFOs (receiver and transmitter).
 */
#define FCR_ENABLE_FIFO BIT(0)

/**
 * @brief The bit for clearing the receiver FIFO of FCR.
 */
#define FCR_CLEAR_RECEIVER_FIFO BIT(1)

/**
 * @brief The bit for clearing the transmitter FIFO of FCR.
 */
#define FCR_CLEAR_TRANSMITTER_FIFO BIT(2)

/**
 * @brief Mask for clearing the bits relative to the trigger level of the FCR (bits 6 and 7), which is equivalent to setting the receiver FIFO trigger level to 1 byte, meaning that an interrupt will be generated as soon as there is at least 1 byte in the receiver FIFO.
 */
#define FCR_1BYTE_TRIGGER_LEVEL 0x3F

/**
 * @brief The offset of the Line Control Register (LCR) from the base address of a UART serial port.
 */
#define LCR_OFFSET 3

#define LCR_CHAR_LENGTH_6 BIT(0)
#define LCR_CHAR_LENGTH_7 BIT(1)
#define LCR_CHAR_LENGTH_8 BIT(1) | BIT(0)
#define LCR_STOP_BIT_2 BIT(2)
#define LCR_ODD_PARITY BIT(3)
#define LCR_EVEN_PARITY BIT(4) | BIT(3)
#define LCR_FORCED1_PARITY BIT(5) | BIT(3)
#define LCR_FORCED0_PARITY BIT(5) | BIT(4) | BIT(3)
#define LCR_CLEAR_EXCEPT_BREAK_CONTROL 0x40

/**
 * @brief The offset of the Line Status Register (LSR) from the base address of a UART serial port. This register provides status information concerning the data transfer
 */
#define LSR_OFFSET 5

#define LSR_DATA_READY BIT(0)
#define LSR_OVERRUN_ERROR BIT(1)
#define LSR_PARITY_ERROR BIT(2)
#define LSR_FRAMING_ERROR BIT(3)

/**
 * @brief The offset of the Divisor Latch LSB (DLL) register from the base address of a UART serial port when DLAB bit of the LCR is set.
 */
#define DLL_OFFSET 0

/**
 * @brief The offset of the Divisor Latch MSB (DLM) register from the base address of a UART serial port when DLAB bit of the LCR is set.
 */
#define DLM_OFFSET 1

/**
 * @brief The bit relative to the DLAB (Divisor Latch Access Bit) in the Line Control Register (LCR) of the serial port. This bit must be set to 1 to access the divisor registers (DLL and DLM) and set the bit rate of the serial port.
 */
#define LCR_DLAB BIT(7)

#define LSR_TRANSMITTER_HOLDING_REGISTER_EMPTY BIT(5)

/**
 * @brief Sets up both the receiver and transmitter FIFOs of the serial port, by writing to the FIFO Control Register (FCR) of the serial port, with the appropriate bits set.
 * @return 0 on success, 1 on failure
 */
int setup_fifos();

/**
 * @brief Sets up the Line Control Register (LCR) of the serial port with the desired settings for character length, stop bits and parity.
 * @param char_length The desired character length.
 * @param stop_bits The desired number of stop bits.
 * @param parity The desired parity setting.
 * @return 0 on success, 1 on failure.
 */
int setup_lcr(int char_length, int stop_bits, int parity);

/**
 * @brief Enables the Received Data Available Interrupt of the IER of the serial port, which allows the serial port to generate an interrupt whenever there is data available to be read from the Receiver Buffer Register (RBR) of the serial port.
 * @return 0 on success, 1 on failure
 */
int enable_received_data_interrupt();

/**
 * @brief Enables the Transmitter Holding Register Empty Interrupt of the IER of the serial port, which allows the serial port to generate an interrupt whenever the Transmitter Holding Register (THR) of the serial port is empty and ready to accept new data to be transmitted.
 * @return 0 on success, 1 on failure 
 */
int enable_transmitter_holding_register_empty_interrupt();

/**
 * @brief Enables the Line Status Interrupt of the IER of the serial port, which allows the serial port to generate an interrupt whenever there is a change in the error bits of the Line Status Register (LSR).
 * @return 0 on success, 1 on failure
 */
int enable_line_status_interrupt();

/**
 * @brief Gets the current value of the Interrupt Enable Register (IER) of the serial port and stores it in the location pointed to by the argument.
 * @param ier The location where the value of the IER will be stored.
 * @return 0 on success, 1 on failure
 */
int get_ier(uint8_t *ier);

/**
 * @brief Gets the current value of the Line Control Register (LCR) of the serial port and stores it in the location pointed to by the argument.
 * @param lcr The location where the value of the LCR will be stored.
 * @return 0 on success, 1 on failure
 */
int get_lcr(uint8_t *lcr);

/**
 * @brief Gets the current value of the Interrupt Identification Register (IIR) of the serial port and stores it in the location pointed to by the argument.
 * @param irr The location where the value of the IIR will be stored.
 * @return 0 on success, 1 on failure
 */
int get_irr(uint8_t *irr);

/**
 * @brief Gets the current value of the Line Status Register (LSR) of the serial port and stores it in the location pointed to by the argument.
 * @param lsr The location where the value of the LSR will be stored.
 * @return 0 on success, 1 on failure
 */
int get_lsr(uint8_t *lsr);

/**
 * @brief Sets the bit rate of the serial port by calculating the appropriate divisor for the desired bit rate and writing it to the Divisor Latch LSB (DLL) and Divisor Latch MSB (DLM) registers of the serial port. This function also sets the DLAB bit of the Line Control Register (LCR) to access the divisor registers and then clears it after setting the bit rate.
 * 
 * @param bit_rate The desired bit rate for the serial port communication.
 * @return 0 on success, 1 on failure
 */
int set_bit_rate(uint16_t bit_rate);

// Uses flag IRQ_EXCLUSIVE because MINIX has a default interrupt handler for the UART.

/**
 * @brief Subscribes to the serial port interrupts exclusively. This function also stores the bit number of the interrupt in the location pointed to by the argument, which can be used later to identify the interrupt in the interrupt handler.
 * @param bit_no Initially, a pointer to the bit position in the interrupt mask to be set to 1 in case of an interrupt. On success, its value is updated with the corresponding bit mask with a 1 in the *bit_no position (i.e., 1 << *bit_no).
 * @return 0 on success, 1 on failure
 */
int serial_port_subscribe_int(uint8_t *bit_no);

/**
 * @brief Gathers setup logic for the serial port in the perspective of a transmitter, which includes setting up the FIFOs, configuring the Line Control Register (LCR) with the desired settings (character length, stop bits, parity), enabling the necessary interrupts (Received Data Available Interrupt and Line Status Interrupt), setting the bit rate of the serial port, and subscribing to the serial port interrupts.
 * 
 * @param bit_no The bit number for the serial port interrupt to pass to the subscribe function, which will be updated with the corresponding bit mask on success.
 * @return 0 on success, 1 on failure
 */
int setup_serial_port_transmitter(uint8_t *bit_no);

/**
 * @brief Gathers setup logic for the serial port in the perspective of a receiver, which includes creating and initializing a receiver queue to store the received data, setting up the FIFOs, configuring the Line Control Register (LCR) with the desired settings (character length, stop bits, parity), enabling the Received Data Available Interrupt and Line Status Interrupt of the serial port, setting the bit rate of the serial port, and subscribing to the serial port interrupts.
 * 
 * @param bit_no The bit number for the serial port interrupt to pass to the subscribe function, which will be updated with the corresponding bit mask on success.
 * @return 0 on success, 1 on failure
 */
int setup_serial_port_receiver(uint8_t *bit_no);

/**
 * @brief Unsubscribes from the serial port interrupts.
 * @return 0 on success, 1 on failure
 */
int serial_port_unsubscribe_int();

/**
 * @brief Undoes the setup of the serial port, unsubscribing from the serial port interrupts, and setting every configuration made to the default state.
 * @return 0 on success, 1 on failure
 */
int serial_port_undo();

/**
 * @brief Gets the queue of data received from the serial port from the receiver perspective.
 * @details Although the FIFO was set to generate an interrupt whenever there is at least 1 byte in the receiver FIFO, it was noticed that sometimes a single interrupt is generated for multiple bytes received in a short time interval. This is the reason why a queue was used to store the received data, so that all the received data can be processed in the interrupt handler, even if it was received in a single interrupt.
 * 
 * @return The queue of data received from the serial port.
 */
Queue get_received_data();

/**
 * @brief Sends data through the serial port, in the perspective of a transmitter. 
 * @details This function waits until the Transmitter Holding Register (THR) of the serial port is empty and ready to accept new data to be transmitted, by checking the corresponding bit in the Line Status Register (LSR) of the serial port, and then writes the data to be transmitted to the THR register of the serial port.
 * @param data The data to be transmitted.
 * @return 0 on success, 1 on failure.
 */
int send_sp_data(uint8_t data);

// To receive data - called after a received data interrupt is generated.
/**
 * @brief Interrupt handler for the serial port. Handles various types of interrupts generated by the serial port, namely the Received Data Available Interrupt, which triggers a read of the received data from the Receiver Buffer Register (RBR) of the serial port and stores it in the receiver queue.
 * @return 0 on success, 1 on failure. 
 */
int serial_port_ih();

#endif /* SERIAL_PORT_H */
